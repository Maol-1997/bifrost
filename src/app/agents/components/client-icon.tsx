import type { ComponentType, SVGProps } from 'react';

import { ClaudeAiIcon } from '@app/components/ui/svgs/claude-ai-icon';
import { CodexDark } from '@app/components/ui/svgs/codex-dark';
import { CursorDark } from '@app/components/ui/svgs/cursor-dark';
import { OpencodeDark } from '@app/components/ui/svgs/opencode-dark';
import type { ClientLogoId } from '@app/api/bifrost';

/**
 * These marks are drawn three different ways, so each one carries the classes
 * that make it legible rather than the tile guessing. Where svgl ships a pair we
 * take the one meant for dark surfaces; the light one is a dark glyph and would
 * vanish into the tile.
 *
 * Generated by
 * `npx shadcn@latest add @svgl/claude-ai @svgl/codex @svgl/cursor @svgl/opencode`.
 */
const clientLogos: Record<ClientLogoId, { Mark: ComponentType<SVGProps<SVGSVGElement>>; className: string }> = {
  // Claude Code has no mark of its own; the Claude sunburst is what it ships
  // under, and its orange is what makes it recognizable at this size.
  'claude-code': { Mark: ClaudeAiIcon, className: 'size-[18px]' },
  codex: { Mark: CodexDark, className: 'size-[18px]' },
  // Cursor's mark carries no fill at all, so left alone it renders black on a
  // black tile. It takes our logo colour the way Linear's mark does.
  cursor: { Mark: CursorDark, className: 'size-[18px] fill-current text-logo' },
  // OpenCode draws its mark on a background plate of its own. Rather than strip
  // it out of the generated file, we let that plate be the tile: it fills the
  // square edge to edge instead of sitting inside ours as a second, smaller one.
  opencode: { Mark: OpencodeDark, className: 'size-full' },
};

/**
 * The tile in front of a client's name. A client we have no mark for keeps its
 * monogram, so the row never renders an empty square.
 */
export function ClientIcon({ logo, monogram }: { logo: ClientLogoId | undefined; monogram: string }): React.JSX.Element {
  const entry = logo ? clientLogos[logo] : undefined;
  return (
    <div className="flex size-8 shrink-0 items-center justify-center overflow-hidden rounded-lg border-[0.5px] border-plate-border bg-white/5 text-xs font-semibold text-app-text-tertiary">
      {entry ? <entry.Mark aria-hidden className={entry.className} /> : monogram}
    </div>
  );
}
